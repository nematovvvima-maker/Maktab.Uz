export function getGradeNumber(gradeStr: string): number {
  const match = gradeStr.match(/\d+/);
  return match ? parseInt(match[0], 10) : 1;
}

export function getSubjectsForGrade(gradeStr: string): string[] {
  const num = getGradeNumber(gradeStr);
  if (num >= 1 && num <= 4) {
    return SUBJECTS_BY_GRADE_LEVEL.elementary;
  } else if (num >= 5 && num <= 6) {
    return SUBJECTS_BY_GRADE_LEVEL.middle;
  } else {
    return SUBJECTS_BY_GRADE_LEVEL.high;
  }
}

